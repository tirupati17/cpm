#!/usr/bin/env python3
"""Install managed, real copies of skills for coding agents, preserving custom folders."""
import os
import shutil
import sys
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = root / 'skills'
marker_name = '.cpm-managed-copy'
if not source.is_dir():
    raise SystemExit(0)
skills = sorted(p for p in source.iterdir() if p.is_dir() and not p.name.startswith('_') and (p / 'SKILL.md').is_file())
lines = ['# Skills index', '', 'Generated by `scripts/link-skills.sh`. Open the matching `SKILL.md` before a task.', '']
for skill in skills:
    desc = next((line.partition(':')[2].strip() for line in (skill / 'SKILL.md').read_text().splitlines() if line.startswith('description:')), '')
    lines.append(f'- **{skill.name}** (`skills/{skill.name}/SKILL.md`): {desc}')
(source / 'INDEX.md').write_text('\n'.join(lines) + '\n')
for relative in os.environ.get('CPM_SKILL_DIRS', '.claude/skills .agents/skills').split():
    destination = root / relative
    if Path(relative).is_absolute() or '..' in Path(relative).parts:
        raise SystemExit('CPM_SKILL_DIRS must contain workspace-relative directories.')
    if destination.is_symlink():
        raise SystemExit(f'{relative} is a symlink; use a real agent skills directory.')
    destination.mkdir(parents=True, exist_ok=True)
    for target in destination.iterdir():
        owned_link = target.is_symlink() and target.resolve() == source / target.name
        owned_copy = not target.is_symlink() and (target / marker_name).is_file()
        if target.name not in {p.name for p in skills} and owned_copy:
            shutil.rmtree(target)
        elif owned_link:
            target.unlink()
    for skill in skills:
        target = destination / skill.name
        if target.is_symlink() or (target.exists() and not (target / marker_name).is_file()):
            print(f'Preserved custom agent skill: {relative}/{skill.name}', file=sys.stderr)
            continue
        def contents(folder):
            return {str(p.relative_to(folder)): p.read_bytes() for p in folder.rglob('*')
                    if p.is_file() and p.name not in {marker_name, '.DS_Store'}
                    and not {'__pycache__', '.git'}.intersection(p.relative_to(folder).parts)}
        if target.exists() and contents(target) == contents(skill):
            continue
        # Replace only changed CPM-owned copies. Remove stale resource files too.
        if target.exists(): shutil.rmtree(target)
        shutil.copytree(skill, target, ignore=shutil.ignore_patterns('__pycache__', '.DS_Store', '.git'))
        (target / marker_name).write_text(f'Generated from skills/{skill.name}; edit the source, then sync.\n')
if '--list' in sys.argv:
    print('\n'.join('  ' + p.name for p in skills))
    print('Skills installed as real folders; no shortcuts or symlinks created.')
